/**
 * Build-time icon asset generator.
 *
 * The docs site cannot read the icon SVGs from the monorepo filesystem at
 * request time — on Cloudflare Workers there is no real filesystem, so
 * `readdir`/`readFile` against `packages/icons/assets/svg` fail and the page
 * 500s (and `/arlo-icons/*` 404s). Instead we resolve everything at build time:
 *
 *   - `lib/generated/icon-data.ts` — the icon name list + animated-icon source,
 *     imported as plain JS (bundled, no fs). Small; committed to the repo.
 *   - `public/arlo-icons/<name>.svg` + `<name>.preview.svg` — the SVGs copied
 *     into `public/` so Cloudflare serves them as static assets (no Worker, no
 *     script-size limit). Large; generated at build and git-ignored.
 *
 * Run automatically via the `build` / `dev` scripts. Safe to re-run.
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const PREVIEW_COLOR = '#18181B';

const appDir = process.cwd();
const repoRoot = appDir.endsWith('apps/www') ? resolve(appDir, '../..') : appDir;
const svgDir = join(repoRoot, 'packages/icons/assets/svg');
const animatedSourcePath = join(
  repoRoot,
  'packages/registry/src/components/animated-icon/animated-icon.tsx',
);

const names = readdirSync(svgDir)
  .filter((file) => file.endsWith('.svg'))
  .map((file) => file.slice(0, -4))
  .sort((a, b) => a.localeCompare(b));

// 1. Static assets served from public/arlo-icons.
const publicDir = join(appDir, 'public/arlo-icons');
rmSync(publicDir, { recursive: true, force: true });
mkdirSync(publicDir, { recursive: true });

for (const name of names) {
  const svg = readFileSync(join(svgDir, `${name}.svg`), 'utf8');
  writeFileSync(join(publicDir, `${name}.svg`), svg);
  // Preview variant bakes a fixed dark fill so `<img>` (which cannot inherit
  // `currentColor`) renders visibly; the gallery flips it with `dark:invert`.
  writeFileSync(join(publicDir, `${name}.preview.svg`), svg.replaceAll('currentColor', PREVIEW_COLOR));
}

// 2. Bundled data module (names + animated-icon source).
const animatedSource = readFileSync(animatedSourcePath, 'utf8');
const generatedDir = join(appDir, 'lib/generated');
mkdirSync(generatedDir, { recursive: true });
writeFileSync(
  join(generatedDir, 'icon-data.ts'),
  `// AUTO-GENERATED by scripts/generate-icon-assets.ts — do not edit by hand.\n` +
    `export const iconNames: string[] = ${JSON.stringify(names)};\n\n` +
    `export const animatedIconSource = ${JSON.stringify(animatedSource)};\n`,
);

console.log(`generate-icon-assets: ${names.length} icons → public/arlo-icons + lib/generated/icon-data.ts`);
